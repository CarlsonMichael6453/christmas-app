export type ThemeColors = {
  bg: string;
  surface: string;
  surfaceAlt: string;
  text: string;
  textMuted: string;
  primary: string;
  onPrimary: string;
  secondary: string;
  onSecondary: string;
  accent: string;
  onAccent: string;
  border: string;
  danger: string;
  success: string;
  card: string;
  snow: string;
  tabBar: string;
  input: string;
  star: string;
  overlay: string;
  gradient: [string, string];
};

export type Theme = {
  id: string;
  name: string;
  description: string;
  isDark: boolean;
  swatches: [string, string, string];
  colors: ThemeColors;
};

function theme(
  partial: Omit<Theme, 'colors' | 'swatches'> & { colors: ThemeColors; swatches?: [string, string, string] },
): Theme {
  return {
    ...partial,
    swatches: partial.swatches ?? [partial.colors.primary, partial.colors.secondary, partial.colors.accent],
  };
}

